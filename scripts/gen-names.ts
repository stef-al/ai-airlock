// Generates src/engine/data/names.generated.ts from the MIT-licensed @faker-js/faker locale data.
// Runs before test/build/metrics (npm "pre" hooks) and from vitest's global setup.
import { mkdirSync, writeFileSync } from 'node:fs';
import * as F from '@faker-js/faker';

const LOCALES = ['en', 'de', 'de_AT', 'de_CH', 'fr', 'fr_BE', 'es', 'it', 'pl', 'cs_CZ', 'sk', 'nl', 'pt_PT', 'pt_BR', 'sv', 'da', 'nb_NO', 'fi', 'hu', 'ro', 'tr', 'en_AU', 'en_CA', 'en_IE', 'en_ZA', 'en_IN'];

function grab(o: unknown, out: string[]): void {
  if (typeof o === 'string') out.push(o);
  else if (Array.isArray(o)) o.forEach((x) => grab(x, out));
  else if (o && typeof o === 'object') Object.values(o).forEach((x) => grab(x, out));
}

const first = new Set<string>();
const last = new Set<string>();
const used: string[] = [];
for (const l of LOCALES) {
  const p = (F as unknown as Record<string, { person?: Record<string, unknown> }>)[l]?.person;
  if (!p) continue;
  const f: string[] = [];
  const s: string[] = [];
  for (const [k, v] of Object.entries(p)) {
    if (/first_name$/.test(k) || k === 'first_name') grab(v, f);
    if (k === 'last_name') grab(v, s);
  }
  if (f.length + s.length) used.push(l);
  const ok = (n: string) => /^\p{Lu}[\p{L}'’-]{2,23}$/u.test(n) && !n.includes('{');
  f.filter(ok).forEach((n) => first.add(n.toLowerCase()));
  s.filter(ok).forEach((n) => last.add(n.toLowerCase()));
}
const fmt = (set: Set<string>) => [...set].sort().join('|');
mkdirSync('src/engine/data', { recursive: true });
writeFileSync(
  'src/engine/data/names.generated.ts',
  `// GENERATED by scripts/gen-names.ts from @faker-js/faker (MIT) locales: ${used.join(', ')}. Do not edit.\n` +
    `export const FIRST_NAMES: string = ${JSON.stringify(fmt(first))};\nexport const LAST_NAMES: string = ${JSON.stringify(fmt(last))};\n`,
);
console.log(`names: ${first.size} first, ${last.size} last (${used.length} locales)`);
